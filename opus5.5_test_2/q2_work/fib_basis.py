"""
Fibonacci fusion-tree basis, F-moves, and check of the sector structure.
Left-to-right (standard) fusion-tree basis of Hom(1, tau^{N}):
  labels x_1 = tau, x_j in {1,tau} = total charge of first j anyons, x_N = 1,
  with x_{j+1} in x_j (x) tau.
"""
import numpy as np
from itertools import product
phi = (1 + 5**0.5) / 2
# F^{tau tau tau}_tau in the intermediate-channel basis (1, tau)
Fm = np.array([[phi**-1, phi**-0.5], [phi**-0.5, -phi**-1]])

def fib(n):
    a, b = 0, 1
    for _ in range(n):
        a, b = b, a + b
    return a

def allowed(x, y):          # y in x (x) tau ?
    return (x == 1 and y == 't') or (x == 't')

def basis(N):
    """list of label tuples (x_1..x_N) with x_1 = t, x_N = 1"""
    out = []
    def rec(seq):
        if len(seq) == N:
            if seq[-1] == 1:
                out.append(tuple(seq))
            return
        for y in (1, 't'):
            if allowed(seq[-1], y):
                rec(seq + [y])
    rec(['t'])
    return out

def pair_projector(N, i, e):
    """Projector onto total channel e of anyons i, i+1 (1-based), in the standard basis.
    Uses F^{x_{i-1} tau tau}_{x_{i+1}}; nontrivial only if x_{i-1} = x_{i+1} = tau."""
    B = basis(N); idx = {b: n for n, b in enumerate(B)}
    P = np.zeros((len(B), len(B)))
    lab = {1: 0, 't': 1}
    for s in B:
        for sp in B:
            # must agree away from position i (0-based index i-1 is x_i)
            if any(s[j] != sp[j] for j in range(N) if j != i - 1):
                continue
            xl = s[i - 2] if i >= 2 else 1      # x_{i-1}; x_0 = vacuum
            xr = s[i]                           # x_{i+1}
            if xl == 't' and xr == 't':
                # 2x2 F-matrix in basis x_i in (1,tau), channels e in (1,tau)
                P[idx[s], idx[sp]] = Fm[lab[s[i - 1]], lab[e]] * Fm[lab[sp[i - 1]], lab[e]]
            else:
                # one-dimensional: channel is fixed
                # (x_{i-1}=1 -> anyons i,i+1 fuse to x_{i+1}; x_{i+1}=1 -> fuse to x_{i-1}... )
                if xl == 1:
                    ch = xr
                elif xr == 1:
                    ch = xl
                else:
                    raise RuntimeError
                P[idx[s], idx[sp]] = 1.0 if (ch == e and s == sp) else 0.0
    return P

def algebra_dim(gens, tol=1e-9):
    """dimension of the unital *-algebra generated by a list of matrices"""
    d = gens[0].shape[0]
    span = [np.eye(d).ravel()]
    def add(M):
        v = M.ravel()
        A = np.array(span).T
        coef, *_ = np.linalg.lstsq(A, v, rcond=None)
        if np.linalg.norm(A @ coef - v) > tol:
            span.append(v); return True
        return False
    for g in gens: add(g)
    changed = True
    while changed:
        changed = False
        cur = [v.reshape(d, d) for v in span]
        for X in cur:
            for g in gens:
                if add(X @ g): changed = True
    return len(span)

if __name__ == "__main__":
    print("F unitary/involutive:", np.allclose(Fm @ Fm, np.eye(2)), np.allclose(Fm, Fm.T))
    for NR, NB in [(2, 2), (2, 3), (3, 2), (3, 3), (4, 2), (3, 4), (4, 4), (5, 3)]:
        N = NR + NB
        B = basis(N)
        m = {a: fib(NR - 1) if a == 1 else fib(NR) for a in (1, 't')}
        n = {a: fib(NB - 1) if a == 1 else fib(NB) for a in (1, 't')}
        D = len(B)
        assert D == fib(N - 1) == m[1] * n[1] + m['t'] * n['t']
        # sector of each basis state = x_{NR}
        sec = np.array([0 if b[NR - 1] == 1 else 1 for b in B])
        genR = [pair_projector(N, i, 1) for i in range(1, NR)]
        genB = [pair_projector(N, i, 1) for i in range(NR + 1, N)]
        # checks: projectors, commute, sector preserving
        for P in genR + genB:
            assert np.allclose(P @ P, P) and np.allclose(P, P.T)
            assert np.allclose(P * (sec[:, None] != sec[None, :]), 0)
        comm = max((np.abs(P @ Q - Q @ P).max() for P in genR for Q in genB), default=0)
        dR = algebra_dim(genR + [np.diag((sec == 0).astype(float))])
        dB = algebra_dim(genB + [np.diag((sec == 0).astype(float))]) if genB else None
        straddle = pair_projector(N, NR, 1)
        mix = np.abs(straddle * (sec[:, None] != sec[None, :])).max()
        print(f"NR={NR} NB={NB}: D={D} m={m[1],m['t']} n={n[1],n['t']}  "
              f"dim<A_R>={dR} (sum m_a^2={m[1]**2+m['t']**2})  dim<A_B>={dB} "
              f"(sum n_a^2={n[1]**2+n['t']**2})  max|[R,B]|={comm:.1e}  straddling op mixes sectors: {mix:.3f}")
